def sub(parent, tag, text=None, **attrs):
    attributes = {k.replace('_', '-'): str(v) for k, v in attrs.items()}
    # Tableau's XML color type accepts lowercase hexadecimal only.
    for key, value in attributes.items():
        if re.fullmatch(r"#[0-9a-fA-F]{6}(?:[0-9a-fA-F]{2})?", value):
            attributes[key] = value.lower()
    node = ET.SubElement(parent, tag, attributes)
    if text is not None:
        node.text = str(text)
    return node


def workbook_xml_errors(book):
    """Check the XML constraints reported by Tableau; not a full schema check."""
    errors = []
    if not book.get("source-build", "").strip():
        errors.append("workbook: missing source-build")
    for node in book.iter():
        for key, value in node.attrib.items():
            if key in {"fontcolor", "color", "tab-color"} or value.startswith("#"):
                if not re.fullmatch(r"#[0-9a-f]{6}(?:[0-9a-f]{2})?", value):
                    errors.append(f"{node.tag}/{key}: invalid color {value}")
    for window in book.findall("./windows/window"):
        children = [node.tag for node in window]
        if window.get("class") == "worksheet":
            valid = children in (["cards"], ["cards", "viewpoint"])
        else:
            valid = children == ["viewpoints", "active", "device-preview"]
        if not valid:
            errors.append(f"window {window.get('name')}: invalid child order {children}")
    return errors


def create_extract(csv_path, types):
    """Store the exact displayed CSV values in a real Tableau Hyper database."""
    frame = pd.read_csv(csv_path, encoding="utf-8-sig")
    path = csv_path.parent / "Extracts" / (csv_path.stem + ".hyper")
    path.parent.mkdir(exist_ok=True)
    sql_types = {"integer": SqlType.big_int(), "real": SqlType.double(), "string": SqlType.text()}
    converters = {"integer": int, "real": float, "string": str}
    table = TableDefinition(TableName("Extract", "Extract"), [
        TableDefinition.Column(field, sql_types[types[field]]) for field in frame.columns])
    rows = [[None if pd.isna(value) else converters[types[field]](value)
             for field, value in zip(frame.columns, row)]
            for row in frame.itertuples(index=False, name=None)]
    # Format 0 preserves compatibility with older Tableau releases. The local
    # TCP option is supported on Windows, macOS and Linux. Telemetry is disabled.
    with HyperProcess(Telemetry.DO_NOT_SEND_USAGE_DATA_TO_TABLEAU,
            parameters={"default_database_version": "0", "use_tcp_port": "auto", "log_config": ""}) as hyper:
        with Connection(hyper.endpoint, path, CreateMode.CREATE_AND_REPLACE) as conn:
            conn.catalog.create_schema("Extract")
            conn.catalog.create_table(table)
            with Inserter(conn, table) as inserter:
                inserter.add_rows(rows)
                inserter.execute()
        # Reopen the saved file; compare all values, not just row counts.
        with Connection(hyper.endpoint, path) as conn:
            restored = conn.execute_list_query('SELECT * FROM "Extract"."Extract"')
            assert sorted(restored, key=repr) == sorted(rows, key=repr), csv_path.name
    return path, {"rows": len(rows), "columns": len(frame.columns),
        "reopened_and_all_values_match_csv": True,
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}


def add_source(root, name, frame, data_folder):
    filename = name + ".csv"
    frame.to_csv(data_folder / filename, index=False, encoding="utf-8-sig", float_format="%.10g")
    datasource = sub(root.find("datasources"), "datasource", caption=name, inline="true",
                     name="textscan."+name, version="10.5")
    connection = sub(datasource, "connection", **{"class":"textscan", "directory":"Data", "filename":filename,
        "password":"", "server":"", "locale":"en_US"})
    relation = sub(connection, "relation", name=name+"#csv", table="["+name+"#csv]", type="table")
    columns = sub(relation, "columns", character_set="UTF-8", header="yes", separator=",", locale="en_US")
    metadata = sub(connection, "metadata-records")
    types = {}
    for i, field in enumerate(frame.columns):
        series = frame[field]
        datatype = "integer" if pd.api.types.is_integer_dtype(series) else "real" if pd.api.types.is_numeric_dtype(series) else "string"
        types[field] = datatype
        sub(columns, "column", name=field, datatype=datatype, ordinal=i)
        record = sub(metadata, "metadata-record", **{"class":"column"})
        for tag, value in [("remote-name",field),("remote-type",20 if datatype=="integer" else 5 if datatype=="real" else 129),
             ("local-name","["+field+"]"),("parent-name","["+name+"#csv]"),("remote-alias",field),
             ("ordinal",i),("local-type",datatype),("aggregation","Sum" if datatype!="string" else "Count"),
             ("contains-null","true")]:
            sub(record,tag,text=value)
    sub(datasource,"aliases",enabled="yes")
    for field,datatype in types.items():
        dim = datatype == "string"
        sub(datasource,"column", name="["+field+"]", datatype=datatype,
            role="dimension" if dim else "measure", type="nominal" if dim else "quantitative")
    extract_path, extract_check = create_extract(data_folder / filename, types)
    extract = sub(datasource, "extract", count="-1", enabled="true", units="records")
    # Keep the original CSV connection for future refreshes, and activate its
    # extract. Merely putting a CSV in a TWBX does not satisfy Tableau Public.
    hyper_connection = ET.SubElement(extract, "connection", {
        "class": "hyper", "dbname": "Data/Extracts/" + extract_path.name,
        "access_mode": "readonly", "authentication": "auth-none",
        "author-locale": "en_US", "default-settings": "yes",
        "schema": "Extract", "tablename": "Extract", "sslmode": "",
        "username": "tableau_internal_user"})
    sub(hyper_connection, "relation", name="Extract", table="[Extract].[Extract]", type="table")
    extract_metadata = copy.deepcopy(metadata)
    for parent in extract_metadata.findall("metadata-record/parent-name"):
        parent.text = "[Extract]"
    hyper_connection.append(extract_metadata)
    return datasource, types, extract_check


def worksheet(workbook, name, source, types, rows=None, cols=None, mark="Automatic", encodings=None, sort=None, kpi=False, row_fields=None):
    dsname = source.get("name")
    ws = sub(workbook.find("worksheets"),"worksheet",name=name)
    layout = sub(ws,"layout-options");title = sub(layout,"title");ft=sub(title,"formatted-text")
    sub(ft,"run",text=name,fontname="Arial",fontsize="12",bold="true",fontcolor="#142C3A")
    table = sub(ws,"table"); view=sub(table,"view")
    sub(sub(view,"datasources"),"datasource",caption=source.get("caption"),name=dsname)
    deps=sub(view,"datasource-dependencies",datasource=dsname)
    used = []
    row_specs = row_fields or ([rows] if rows else [])
    for spec in [*row_specs,cols,*list((encodings or {}).values())]:
        if spec and spec not in used: used.append(spec)
    refs={}
    added_columns=set()
    for field,agg in used:
        if field not in added_columns:
            deps.append(copy.deepcopy(source.find(f"column[@name='[{field}]']")))
            added_columns.add(field)
        datatype=types[field]
        derivation={"none":"None","sum":"Sum","avg":"Avg","min":"Min"}[agg]
        kind="nk" if agg=="none" else "qk"
        inst=f"[{agg}:{field}:{kind}]"
        sub(deps,"column-instance",column="["+field+"]",derivation=derivation,name=inst,pivot="key",
            type="nominal" if agg=="none" else "quantitative")
        refs[(field,agg)]=f"[{dsname}].{inst}"
    if sort:
        sub(view,"sort",**{"class":"computed","column":refs[sort[0]],"direction":"DESC","using":refs[sort[1]]})
    sub(view,"aggregation",value="true")
    style=sub(table,"style")
    rule=sub(style,"style-rule",element="worksheet")
    sub(rule,"format",attr="font-family",value="Arial")
    sub(rule,"format",attr="font-size",value="10")
    sub(rule,"format",attr="color",value="#183747")
    pane=sub(sub(table,"panes"),"pane",selection_relaxation_option="selection-relaxation-allow")
    sub(sub(pane,"view"),"breakdown",value="auto")
    sub(pane,"mark",**{"class":mark})
    enc=sub(pane,"encodings")
    for channel,spec in (encodings or {}).items():sub(enc,"lod" if channel=="detail" else channel,column=refs[spec])
    ps=sub(pane,"style");pr=sub(ps,"style-rule",element="mark")
    sub(pr,"format",attr="color",value="#4F708B")
    if kpi or "text" in (encodings or {}):
        sub(pr,"format",attr="mark-labels-show",value="true")
        sub(pr,"format",attr="font-size",value="24" if kpi else "10")
    elif mark=="Circle":
        sub(pr,"format",attr="size",value="0.35")
        sub(pr,"format",attr="opacity",value="0.75")
    row_expression = " / ".join(refs[spec] for spec in row_specs)
    sub(table,"rows",text="("+row_expression+")" if len(row_specs)>1 else row_expression)
    sub(table,"cols",text=refs.get(cols,""))
    return ws


def dashboard_data(summary, peers, watch):
    """Two comparisons: counts for the whole group, balances for five matches."""
    eligible = peers.loc[peers.eligible.eq(1)].copy()
    higher = int(eligible.deposit_yoy.ge(0).sum())
    lower = int(eligible.deposit_yoy.lt(0).sum())
    unchanged = int(eligible.deposit_yoy.eq(0).sum())
    counts = pd.DataFrame({
        "Deposit change": ["Higher or unchanged deposits" if unchanged else "Higher deposits", "Lower deposits"],
        "Number of banks": [higher, lower],
        "Label": [f"{n:,} banks ({n / len(eligible):.1%})" for n in [higher, lower]],
    })
    top = watch.sort_values(["deposit_loss_k", "cert"], ascending=[False, True]).head(5).copy()
    current = pd.Timestamp(summary["as_of"])
    prior = current - pd.DateOffset(years=1)
    records = []
    for rank, row in enumerate(top.itertuples(), 1):
        name = row.bank_name.strip().title().replace("National Assn", "NA").replace(" Na", " NA")
        label = f"{rank}. {name}\n${row.deposit_loss_m:,.0f}m lower ({-row.deposit_yoy:.1%})"
        for date, value in [(prior, row.deposits_prior_year_k), (current, row.deposits_k)]:
            records.append({
                "Bank": label, "FDIC certificate": int(row.cert),
                "Report date": date.strftime("%b %Y"),
                "Deposits (USD millions)": value / 1000,
                "Balance label": f"${value / 1000:,.0f}m",
                "Deposit decline (USD millions)": row.deposit_loss_m,
                "Deposit change (%)": row.deposit_yoy * 100,
                "Net loans per 100 dollars of deposits": row.loan_to_deposit * 100,
            })
    balances = pd.DataFrame(records)
    assert len(eligible) == summary["eligible_banks"]
    assert higher + lower == len(eligible)
    assert lower == summary["contracting_banks"]
    assert len(watch) == int(peers.review_flag.sum()) == summary["review_banks"]
    assert top.review_flag.eq(1).all()
    assert balances.groupby("FDIC certificate").size().eq(2).all()
    return counts, balances, top, prior, current


def text_zone(parent, identifier, x, y, w, h, lines):
    zone = sub(parent, "zone", id=identifier, x=x, y=y, w=w, h=h, type="text")
    formatted = sub(zone, "formatted-text")
    for text, size, bold in lines:
        sub(formatted, "run", text=text, fontname="Arial", fontsize=size,
            bold=str(bold).lower(), fontcolor="#293640")
    return zone


def build_tableau(summary, counts, balances, top, prior, current, retrieved):
    folder = ROOT / "tableau"
    data = folder / "Data"
    data.mkdir(parents=True, exist_ok=True)
    for name in ["Peers.csv", "KPIs.csv", "Trend.csv", "Review.csv", "Segments.csv"]:
        (data / name).unlink(missing_ok=True)
    book = ET.Element("workbook", {"version": "10.5", "source-platform": "win",
        "source-build": TABLEAU_SOURCE_BUILD,
        "xmlns:user": "http://www.tableausoftware.com/xml/user"})
    sub(book, "preferences"); sub(book, "datasources"); sub(book, "worksheets")
    cs, ct, count_extract = add_source(book, "DepositCounts", counts, data)
    bs, bt, balance_extract = add_source(book, "BankBalances", balances, data)
    count_title = "How many banks had higher or lower deposits?"
    balance_title = f"Five largest dollar declines on the {summary['review_banks']}-bank review list"
    worksheet(book, count_title, cs, ct, rows=("Deposit change", "none"),
        cols=("Number of banks", "sum"), mark="Bar",
        encodings={"text": ("Label", "none"), "color": ("Deposit change", "none")},
        sort=(("Deposit change", "none"), ("Number of banks", "sum")))
    worksheet(book, balance_title, bs, bt,
        row_fields=[("Bank", "none"), ("Report date", "none")],
        cols=("Deposits (USD millions)", "sum"), mark="Bar",
        encodings={"text": ("Balance label", "none"), "color": ("Report date", "none")})
    names = [count_title, balance_title]
    dashboard = sub(sub(book, "dashboards"), "dashboard", name="Bank Deposits and Lending")
    sub(dashboard, "style")
    sub(dashboard, "size", maxheight=1000, maxwidth=1440, minheight=1000, minwidth=1440)
    zones = sub(dashboard, "zones")
    base = sub(zones, "zone", h=100000, w=100000, x=0, y=0, id=0, type="layout-basic")
    period = f"{prior.strftime('%B %Y')} vs {current.strftime('%B %Y')}"
    text_zone(base, 1, 2000, 1200, 96000, 8500, [
        ("Where are bank deposits falling?\n", 23, True),
        (f"{period} · U.S. banks with $1bn–under $10bn in assets\n", 12, False),
        ("Deposits are money held in bank accounts.", 11, False)])
    text_zone(base, 2, 2000, 11500, 56000, 5500, [
        (f"{summary['eligible_banks']:,} banks have both dates available.\n", 12, True),
        (f"{summary['latest_peer_banks'] - summary['eligible_banks']} of "
         f"{summary['latest_peer_banks']:,} banks lacks a prior-year comparison and is excluded.", 10, False)])
    for identifier, name, position in [
        (3, count_title, (1500, 18500, 57500, 24000)),
        (4, balance_title, (1500, 52000, 97000, 35500))]:
        x, y, w, h = position
        zone = sub(base, "zone", id=identifier, name=name, x=x, y=y, w=w, h=h)
        style = sub(zone, "zone-style")
        sub(style, "format", attr="border-style", value="none")
        sub(style, "format", attr="margin", value="8")
    cut = summary["loan_to_deposit_threshold"] * 100
    text_zone(base, 5, 63000, 11500, 34000, 31500, [
        ("Which banks warrant a closer look?\n\n", 13, True),
        (f"{summary['review_banks']} of the {summary['contracting_banks']} declining banks\n", 23, True),
        (f"also had at least ${cut:.2f} of net loans for every $100 of deposits.\n\n", 12, False),
        (f"The cutoff separates the top {(1-summary['threshold_quantile'])*100:g}% of net loan/deposit ratios in this size group.\n\n", 11, False),
        ("The review list identifies joint conditions; it does not establish financial distress.", 11, False)])
    text_zone(base, 6, 2000, 45000, 96000, 5500, [
        ("Which five banks on the review list had the largest dollar declines?\n", 14, True),
        ("Each pair compares the same bank on the two June 30 dates. USD millions; dollar amounts rounded independently.", 11, False)])
    text_zone(base, 7, 2000, 90000, 96000, 8800, [
        ("Deposit changes can reflect mergers, transfers, business models, and other funding sources.\n", 11, False),
        ("Bank names refer to individual FDIC entities. The Wells Fargo entry is a subsidiary.\n", 10, False),
        (f"Source: FDIC BankFind financials API. Extracted {retrieved} UTC. A saved snapshot of quarter-end balances.", 10, False)])
    windows = sub(book, "windows", source_height=32)
    win = sub(windows, "window", **{"class": "dashboard", "maximized": "true",
        "name": "Bank Deposits and Lending"})
    viewpoints = sub(win, "viewpoints")
    for name in names:
        sub(sub(viewpoints, "viewpoint", name=name), "zoom", type="entire-view")
    sub(win, "active", id=0)
    sub(sub(win, "device-preview"), "device", is_portrait="true", type="Phone")
    for name in names:
        window = sub(windows, "window", **{"class": "worksheet", "name": name})
        cards = sub(window, "cards")
        left = sub(sub(cards, "edge", name="left"), "strip", size=200)
        for card_type in ["pages", "filters", "marks"]:
            sub(left, "card", type=card_type)
        top_edge = sub(cards, "edge", name="top")
        for card_type in ["columns", "rows"]:
            sub(sub(top_edge, "strip", size=2147483647), "card", type=card_type)
        sub(sub(window, "viewpoint"), "zoom", type="entire-view")
    errors = workbook_xml_errors(book)
    if errors:
        raise ValueError("Invalid Tableau workbook XML:\n" + "\n".join(errors))
    ET.indent(book, space="  ")
    twb = folder / "Bank_Funding_Monitor.twb"
    ET.ElementTree(book).write(twb, encoding="utf-8", xml_declaration=True)
    packaged = folder / "Bank_Funding_Monitor.twbx"
    staging = packaged.with_suffix(".twbx.building")
    with zipfile.ZipFile(staging, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.write(twb, twb.name)
        for file in sorted(data.rglob("*")):
            if file.is_file() and file.suffix in {".csv", ".hyper"}:
                archive.write(file, "Data/" + file.relative_to(data).as_posix())
    check = ET.parse(twb)
    sheets = {sheet.get("name") for sheet in check.findall("./worksheets/worksheet")}
    assert len(sheets) == 2
    for zone in check.findall(".//zone[@name]"):
        assert zone.get("name") in sheets
    for connection in check.findall(".//connection"):
        if connection.get("class") == "hyper":
            assert (folder / connection.get("dbname")).is_file()
        else:
            assert (folder / connection.get("directory") / connection.get("filename")).is_file()
    for source in check.findall("./datasources/datasource"):
        assert source.find("extract").get("enabled") == "true"
        assert source.find("extract/connection").get("class") == "hyper"
    with zipfile.ZipFile(staging) as archive:
        assert archive.testzip() is None
        assert len([name for name in archive.namelist() if name.endswith(".csv")]) == 2
        assert len([name for name in archive.namelist() if name.endswith(".hyper")]) == 2
        assert not workbook_xml_errors(ET.fromstring(archive.read(twb.name)))
    staging.replace(packaged)
    validation = {"xml_parsed": True, "worksheets": 2, "dashboards": 1,
        "embedded_csv_sources": 2, "package_crc_ok": True,
        "enabled_hyper_extracts": 2, "hyper_api_version": version("tableauhyperapi"),
        "extract_checks": {"DepositCounts": count_extract, "BankBalances": balance_extract},
        "chart_counts_reconciled": True, "five_banks_have_two_dates_each": True,
        "reported_xml_constraints": {"source_build_present": True,
            "all_hex_colors_lowercase": True, "worksheet_cards_before_viewpoint": True,
            "dashboard_window_child_order": True, "errors": []},
        "xml_validation_scope": "Targeted checks for reported errors; not a full Tableau schema validation",
        "native_tableau_open_test": "not performed; Tableau is not installed in this environment"}
    (ROOT / "reports/tableau_validation.json").write_text(json.dumps(validation, indent=2))


